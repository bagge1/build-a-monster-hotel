"""Bundles the Luau tests (D-17) into one chunk for Studio.

    python tools/test_bundle.py [name ...]   ->  src/server/TestBundle.luau
    python tools/test_bundle.py --clean      ->  deletes it

tests/harness.luau, then every tests/<name>.spec.luau (all of them, or the
named ones) each inside do ... end, then `return summary()`, written as a
ModuleScript Rojo syncs into Studio (gitignored, never committed, required by
nothing in the game). Claude then starts a playtest and runs, with the Studio MCP
against the Server datamodel (the Edit one keeps stale modules),

    return require(game.ServerScriptService.Server.TestBundle:Clone())

and gets "<n> passed, <m> failed" and one
FAIL line per failure, then --clean. See tests/README.md.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TESTS = ROOT / 'tests'
OUT = ROOT / 'src' / 'server' / 'TestBundle.luau'
if sys.argv[1:] == ['--clean']:
    OUT.unlink(missing_ok=True)
    sys.exit(0)
names = sys.argv[1:]
specs = sorted(TESTS.glob('*.spec.luau'))
if names:
    specs = [p for p in specs if p.name[:-len('.spec.luau')] in names]
parts = ['--!nocheck\n-- GENERATED by tools/test_bundle.py; gitignored. Delete with --clean.\n',
         (TESTS / 'harness.luau').read_text(encoding='utf-8')]
for spec in specs:
    parts.append(f'-- {spec.name}\ndo\n{spec.read_text(encoding="utf-8")}\nend\n')
parts.append('return summary()\n')
OUT.write_text('\n'.join(parts), encoding='utf-8')
print(f'{OUT.relative_to(ROOT)}: {len(specs)} spec files')
